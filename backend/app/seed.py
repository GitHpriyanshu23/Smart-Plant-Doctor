def build_thresholds_from_alert_config() -> dict[str, dict]:
    result = {}
    for species, t in PLANT_THRESHOLDS.items():
        sun = t.get("sunlight", {"min": 4, "max": 8, "ideal": 6})
        result[species] = {
            "soil_moisture": t["soil_moisture"],
            "temperature": t["temperature"],
            "humidity": t["humidity"],
            "light": {
                "min": hours_to_lux(sun["min"]),
                "max": hours_to_lux(sun["max"]),
                "ideal": hours_to_lux(sun["ideal"]),
            },
        }
    return result


def seed_species_profiles(db):
    from app.models import SpeciesProfile

    if db.query(SpeciesProfile).count() > 0:
        return

    thresholds_map = build_thresholds_from_alert_config()
    for species, thresholds in thresholds_map.items():
        profile = SpeciesProfile(
            species=species,
            thresholds=thresholds,
            care_guide=SPECIES_CARE_GUIDES.get(species, f"# {species}\n\nCare information coming soon."),
            seasonal_tips=SEASONAL_TIPS.get(species, ""),
            common_diseases=COMMON_DISEASES.get(species, {}),
        )
        db.add(profile)
    db.commit()
